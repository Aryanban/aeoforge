"""Cloudflare-grade AEO & Agent-Readiness Recommendation Engine.
Produces 5-6 prioritized, high-impact recommendations with simulated score boosts,
actionable code snippets, and Cloudflare/Vercel firewall configuration rules.
"""

from typing import Dict, Any, List, Optional
from pydantic import BaseModel


class RecommendationItem(BaseModel):
    id: str
    title: str
    impact: str  # "critical", "high", "medium", "quick_win"
    score_boost: float
    category: str
    description: str
    action_type: str  # "code_snippet", "cloudflare_waf", "llms_txt", "ast_patch"
    code_snippet: Optional[str] = None
    target_file: Optional[str] = None


def generate_recommendations(
    url: str,
    overall_score: float,
    pillars: Dict[str, Any],
    traps: list,
    interactive_marks: list
) -> tuple[List[RecommendationItem], float]:
    """Analyze pillar details and return prioritized recommendations with simulated max score."""
    p_a = pillars.get("pillar_a_citability", {})
    p_b = pillars.get("pillar_b_navigability", {})
    p_c = pillars.get("pillar_c_protocols", {})
    p_d = pillars.get("pillar_d_structured_data", {})

    items: List[RecommendationItem] = []
    accumulated_boost = 0.0

    # 1. Machine Protocols: /llms.txt
    if not p_c.get("details", {}).get("has_llms_txt", False):
        boost = 12.0
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="publish_llms_txt",
            title="Publish Standard /llms.txt Agent Directory",
            impact="high",
            score_boost=boost,
            category="Machine Protocols",
            target_file="public/llms.txt",
            description="Autonomous web agents and answer engines (Meta AI, Perplexity) lack a fast, curated markdown directory. Serving /llms.txt slashes agent token overhead by 80%.",
            action_type="llms_txt",
            code_snippet=f"# {url}\n> Machine-readable agent directory generated by AEOForge.\n\n## Core Resources\n- [/docs](/docs): Developer documentation\n- [/api](/api): REST and WebMCP specifications\n"
        ))

    # 2. WAF & Bot Allow-List: Cloudflare / Vercel
    if not p_c.get("details", {}).get("ai_bots_allowed", True) or any(t.get("category") == "firewall_block" for t in traps):
        boost = 10.0
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="allow_ai_bots_waf",
            title="Configure Cloudflare WAF to Allow Verified AI Bots",
            impact="high",
            score_boost=boost,
            category="WAF & Security",
            target_file="Cloudflare WAF Expression",
            description="Your firewall or bot management blocks AI crawlers from indexing and citing your pages. Configure Cloudflare to skip bot challenges for verified AI agents (Meta-ExternalAgent, PerplexityBot, GPTBot).",
            action_type="cloudflare_waf",
            code_snippet="""// Cloudflare Custom Rule (WAF -> Custom Rules -> Create Rule)
Expression: (cf.client.bot or http.user_agent contains "Meta-ExternalAgent" or http.user_agent contains "PerplexityBot" or http.user_agent contains "GPTBot")
Action: Skip -> All Security Features (Bot Fight Mode, Challenge)"""
        ))

    # 3. Direct Answer Capsule for AEO
    if not p_a.get("details", {}).get("has_answer_capsule", False):
        boost = 8.0
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="add_answer_capsules",
            title="Inject 35–65 Word Direct Answer Capsules under H2s",
            impact="high",
            score_boost=boost,
            category="Citability & AEO",
            target_file="index.html / Article Template",
            description="Answer engines prioritize passages that answer user queries within the first 35-65 words. Add direct factual capsules immediately beneath primary headings.",
            action_type="code_snippet",
            code_snippet='<div class="aeo-answer-capsule">\n  <p><strong>[Topic Definition]:</strong> Concise, 35-to-65 word factual explanation providing the exact entity relationship and core benefit without marketing filler.</p>\n</div>'
        ))

    # 4. Schema.org Knowledge Graph
    schemas = p_d.get("details", {}).get("schema_types", [])
    if len(schemas) == 0:
        boost = 7.5
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="inject_schema_jsonld",
            title="Deploy Schema.org JSON-LD Knowledge Graph",
            impact="medium",
            score_boost=boost,
            category="Structured Data",
            target_file="index.html (<head> tag)",
            description="Search and answer engines rely on JSON-LD graphs (WebSite, Organization, FAQPage) for entity disambiguation and rich citations.",
            action_type="code_snippet",
            code_snippet=f"""<script type="application/ld+json">
{{
  "@context": "https://schema.org",
  "@graph": [
    {{
      "@type": "WebSite",
      "url": "{url}",
      "name": "Target Website"
    }},
    {{
      "@type": "Organization",
      "url": "{url}",
      "name": "Target Website Entity"
    }}
  ]
}}
</script>"""
        ))

    # 5. Semantic HTML5 Landmarks
    if p_b.get("score", 0) < 20.0:
        boost = 6.0
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="semantic_landmarks",
            title="Wrap Core Layout in Semantic HTML5 (<main>, <nav>, <article>)",
            impact="quick_win",
            score_boost=boost,
            category="DOM & Navigability",
            target_file="src/App.tsx / Base Layout",
            description="Autonomous web agents waste tokens and lose grounding when DOM elements lack standard ARIA and semantic landmarks.",
            action_type="code_snippet",
            code_snippet="""<!-- Semantic Layout Structure for Web Agents -->
<nav role="navigation" aria-label="Main Navigation">...</nav>
<main role="main" id="primary-content">
  <article><h1>Page Headline</h1><p>Content...</p></article>
</main>"""
        ))

    # 6. Navigation Traps & Modal Overlays
    if traps:
        boost = 5.0
        accumulated_boost += boost
        items.append(RecommendationItem(
            id="resolve_navigation_traps",
            title=f"Automate Dismissal for {len(traps)} Navigation Trap(s)",
            impact="critical",
            score_boost=boost,
            category="Agent Traps",
            target_file="Cookie / Modal Handler",
            description="Full-page modal popups, cookie walls, or interstitial traps hijack agent focus, causing navigation timeouts and crawler abandonment.",
            action_type="code_snippet",
            code_snippet="""// Agent Dismissal Helper (Run before main task):
const dismissBtn = document.querySelector("#onetrust-accept-btn-handler, .cookie-accept, button[aria-label*='close' i]");
if (dismissBtn) dismissBtn.click();"""
        ))

    # Ensure at least 5 recommendations exist by adding proactive outranking tips
    if len(items) < 5:
        items.append(RecommendationItem(
            id="expose_webmcp_tools",
            title="Expose REST / WebMCP Endpoints for Autonomous Tool Use",
            impact="medium",
            score_boost=4.5,
            category="API Discovery",
            target_file="public/agent-spec.json",
            description="Allow AI agents to query your site via structured machine APIs rather than fragile visual DOM scraping.",
            action_type="code_snippet",
            code_snippet='<link rel="service-desc" type="application/json" href="/agent-spec.json" title="WebMCP Tool Specifications">'
        ))

    potential_score = min(100.0, round(overall_score + accumulated_boost, 1))
    return items, potential_score
